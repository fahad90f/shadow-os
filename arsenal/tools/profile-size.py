"""Compute the download and installed size of every Arsenal profile from APT data.

    arsenal/tools/profile-size.py [--profiles-dir DIR] [--no-recommends]
                                  [--json FILE] [--write]

For each profile the tools declared for the native architecture are handed to
`apt-get install --simulate` (nothing is installed, no root is needed). APT
answers with the complete set of packages it would install on *this* system,
dependencies included; their `Size` (download) and `Installed-Size` fields from
`apt-cache show` are added up.

The result therefore depends on what is already installed where the script
runs. Run in the minimal build chroot it is an upper bound for a desktop
installation, which already has many of the libraries:

    scripts/dev.sh exec --dir arsenal -- python3 /src/arsenal/tools/profile-size.py

--write stores the figures in profiles/sizes.json (used by gen-profiles-doc.py);
the Arsenal manager does not read that file — it asks APT on the running system.

Exit status: 0 computed, 1 APT could not resolve a profile, 2 bad input.
"""
import argparse
import datetime
import json
import os
import re
import subprocess
import sys

sys.dont_write_bytecode = True

import arsenal_manifest as am

INST_LINE = re.compile(r"^Inst (\S+) (?:\[[^\]]*\] )?\((\S+) ")


def native_architecture():
    result = subprocess.run(["dpkg", "--print-architecture"], capture_output=True, text=True, check=False)
    return result.stdout.strip() or "amd64"


def simulate_install(packages, recommends=True):
    """[(name, version)] APT would install for 'packages', or raise ManifestError."""
    command = ["apt-get", "install", "--simulate", "--quiet", "--quiet"]
    if not recommends:
        command.append("--no-install-recommends")
    environment = dict(os.environ, LC_ALL="C.UTF-8", DEBIAN_FRONTEND="noninteractive")
    result = subprocess.run(command + sorted(packages), capture_output=True, text=True, check=False,
                            env=environment)
    if result.returncode != 0:
        detail = (result.stderr.strip() or result.stdout.strip()).splitlines()
        raise am.ManifestError("apt-get --simulate failed: " + " / ".join(detail[-4:]))
    planned = []
    for line in result.stdout.splitlines():
        match = INST_LINE.match(line)
        if match:
            planned.append((match.group(1), match.group(2)))
    return planned


def package_sizes(planned):
    """(download bytes, installed bytes) over [(name, version)]."""
    download = installed = 0
    for start in range(0, len(planned), 200):
        chunk = [f"{name}={version}" for name, version in planned[start:start + 200]]
        result = subprocess.run(["apt-cache", "show"] + chunk, capture_output=True, text=True, check=False)
        for line in result.stdout.splitlines():
            if line.startswith("Size: "):
                download += int(line[6:])
            elif line.startswith("Installed-Size: "):
                installed += int(line[16:]) * 1024
    return download, installed


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--profiles-dir", default=am.PROFILES_DIR)
    parser.add_argument("--no-recommends", action="store_true",
                        help="leave out Recommends of the tools (APT's default is to install them)")
    parser.add_argument("--json", metavar="FILE", help="write the result to FILE")
    parser.add_argument("--write", action="store_true", help="write the result to <profiles-dir>/sizes.json")
    args = parser.parse_args()

    try:
        profiles = am.load_profiles(args.profiles_dir)
    except am.ManifestError as error:
        print(f"profile-size: {error}", file=sys.stderr)
        return 2

    arch = native_architecture()
    report = {
        "schema": 1,
        "comment": "Generated by arsenal/tools/profile-size.py. Sizes are what APT would download and "
                   "install on the system the script ran on (dependencies included).",
        "architecture": arch,
        "recommends": not args.no_recommends,
        "generated": datetime.date.today().isoformat(),
        "profiles": {},
    }
    failed = False
    print(f"{'profile':<11}{'tools':>6}{'packages':>10}{'download':>12}{'installed':>12}")
    for ident in profiles:
        tools = [t["package"] for t in am.effective_tools(profiles, ident)
                 if arch in am.tool_architectures(t)]
        try:
            planned = simulate_install(tools, recommends=not args.no_recommends)
        except am.ManifestError as error:
            print(f"profile-size: {ident}: {error}", file=sys.stderr)
            failed = True
            continue
        download, installed = package_sizes(planned)
        report["profiles"][ident] = {
            "tools": len(tools),
            "packagesToInstall": len(planned),
            "downloadBytes": download,
            "installedBytes": installed,
        }
        print(f"{ident:<11}{len(tools):>6}{len(planned):>10}{am.format_bytes(download):>12}"
              f"{am.format_bytes(installed):>12}")

    text = json.dumps(report, indent=2) + "\n"
    for path in filter(None, [args.json, os.path.join(args.profiles_dir, "sizes.json") if args.write else None]):
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(text)
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())

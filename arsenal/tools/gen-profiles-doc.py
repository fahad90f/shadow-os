"""Generate arsenal/docs/profiles.md from the profile manifests.

    arsenal/tools/gen-profiles-doc.py            # rewrite arsenal/docs/profiles.md
    arsenal/tools/gen-profiles-doc.py --check    # exit 1 if the file is out of date
    arsenal/tools/gen-profiles-doc.py --stdout

Sizes are taken from profiles/sizes.json when that file exists (written by
profile-size.py --write); without it the size column is left out.
"""
import argparse
import os
import sys

sys.dont_write_bytecode = True

import arsenal_manifest as am

OUTPUT = os.path.join(am.ARSENAL_DIR, "docs", "profiles.md")

INTERFACE = {"cli": "CLI", "gui": "GUI", "both": "GUI + CLI"}
REASON = {
    "not-in-debian": "not packaged in Debian",
    "not-in-debian-main": "not in Debian main",
    "proprietary": "proprietary",
    "vendor-terms": "vendor licence terms",
}


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def load_sizes(profiles_dir):
    path = os.path.join(profiles_dir, "sizes.json")
    if not os.path.isfile(path):
        return None
    try:
        return am.load_json(path)
    except am.ManifestError:
        return None


def generate(profiles, categories, sizes):
    category_name = {c["id"]: c["name"] for c in categories}
    category_order = [c["id"] for c in categories]
    out = ["# NEXUS Arsenal profiles", "",
           "<!-- Generated by arsenal/tools/gen-profiles-doc.py from arsenal/profiles/*.json. Do not edit. -->", "",
           "Every tool below is a package in Debian 13 \"trixie\" `main`, installed on demand through the",
           "package manager: `sudo apt install nexus-arsenal-<profile>` or the NEXUS Arsenal application.",
           "Nothing is installed by default. Use the tools only on systems you own or have written",
           "permission to test — see [legal-use.md](legal-use.md).", ""]

    out += ["## Overview", ""]
    header = "| Profile | Metapackage | Tools | Not packaged |"
    rule = "|---|---|---:|---:|"
    if sizes:
        header += " Download | Installed |"
        rule += "---:|---:|"
    out += [header, rule]
    for ident, manifest in profiles.items():
        row = (f"| [{cell(manifest['name'])}](#{ident}) | `{manifest['metapackage']}` | "
               f"{len(am.effective_tools(profiles, ident))} | {len(am.effective_external(profiles, ident))} |")
        if sizes:
            figures = sizes.get("profiles", {}).get(ident)
            row += (f" {am.format_bytes(figures['downloadBytes'])} | {am.format_bytes(figures['installedBytes'])} |"
                    if figures else " — | — |")
        out.append(row)
    out.append("")
    if sizes:
        out += [f"Sizes: what APT would download and install for the whole profile, dependencies and",
                f"Recommends included, in the NEXUS build chroot ({sizes.get('architecture', 'amd64')}; "
                f"computed {sizes.get('generated', '?')} by `tools/profile-size.py`). A desktop installation",
                "already has many of the libraries, so the real figures are lower; the Arsenal application",
                "shows them for the running system.", ""]

    for ident, manifest in profiles.items():
        out += [f'<a id="{ident}"></a>', f"## {manifest['name']}", "", manifest["description"], "",
                f"Install: `sudo apt install {manifest['metapackage']}`", ""]
        includes = manifest.get("includes", [])
        if includes:
            out += ["Combines the profiles: " + ", ".join(f"[{profiles[i]['name']}](#{i})" for i in includes) + ".",
                    ""]
            continue
        tools = am.own_tools(manifest)
        used = [c for c in category_order if any(t["category"] == c for t in tools)]
        used += sorted({t["category"] for t in tools} - set(used))
        for category in used:
            out += [f"### {category_name.get(category, category)}", "",
                    "| Tool | Package | Interface | Architectures | What it is for |", "|---|---|---|---|---|"]
            for tool in tools:
                if tool["category"] != category:
                    continue
                arches = ", ".join(am.tool_architectures(tool))
                out.append(f"| [{cell(tool['name'])}]({tool['homepage']}) | `{tool['package']}` | "
                           f"{INTERFACE[tool['interface']]} | {arches} | {cell(tool['summary'])} |")
            out.append("")
        external = manifest.get("external", [])
        if external:
            out += ["### Not installable from NEXUS repositories", "",
                    "Well-known tools of this field that are not in Debian main. NEXUS does not download or",
                    "repackage them; follow the official instructions.", "",
                    "| Tool | Why there is no package | Licence | Official source |", "|---|---|---|---|"]
            for entry in external:
                out.append(f"| [{cell(entry['name'])}]({entry['homepage']}) | {REASON[entry['why']['reason']]}: "
                           f"{cell(entry['why']['text'])} | {cell(entry['license'])} | <{entry['how']['url']}> |")
            out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--profiles-dir", default=am.PROFILES_DIR)
    parser.add_argument("--output", default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--stdout", action="store_true")
    args = parser.parse_args()
    try:
        profiles = am.load_profiles(args.profiles_dir)
        categories = am.load_categories(args.profiles_dir)
    except am.ManifestError as error:
        print(f"gen-profiles-doc: {error}", file=sys.stderr)
        return 2
    text = generate(profiles, categories, load_sizes(args.profiles_dir))
    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        try:
            with open(args.output, encoding="utf-8") as handle:
                current = handle.read()
        except OSError:
            current = None
        if current != text:
            print(f"gen-profiles-doc: {args.output} is out of date; run arsenal/tools/gen-profiles-doc.py",
                  file=sys.stderr)
            return 1
        print(f"gen-profiles-doc: {args.output} is up to date")
        return 0
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"gen-profiles-doc: wrote {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Generate the Debian control stanzas of the SHADOW Arsenal packages.

    arsenal/tools/gen-control.py            # rewrite arsenal/packaging/control.in
    arsenal/tools/gen-control.py --check    # exit 1 if control.in is out of date
    arsenal/tools/gen-control.py --stdout

Output: one stanza each for

    shadow-arsenal            the manager application (arsenal/manager)
    shadow-arsenal-data       the profile manifests, /usr/share/shadow/arsenal/profiles
    shadow-arsenal-<id>       one metapackage per profile

The stanzas are meant to be merged into debian/control of the shadow-os source
package (they use its substitution variables).

Packaging decisions, all made here so that they are made once:

Architecture
    A metapackage is `Architecture: all` when every tool it lists exists on
    all SHADOW architectures. As soon as one tool is restricted with
    "architectures" in the manifest the metapackage becomes `Architecture: any`
    and that tool is listed as `package [arch ...]`. The restriction is
    evaluated by dpkg-gencontrol for the architecture being built, which is
    only correct for an arch-specific binary package: in an `all` package the
    restriction would be resolved once, for the architecture of the machine
    that happened to build it, and arm64 systems would get an uninstallable
    (Depends) or silently wrong (Recommends) package.

Depends
    Depends:    shadow-arsenal-data — the manifest that says what the profile is,
                so every front end can show it; for a profile that "includes"
                others (complete), the metapackages of those profiles (such a
                profile is defined as "all of these"); and the tools of the
                profile themselves. Shadow OS is a maximum-coverage security
                distribution: a profile is meant to install every one of its
                tools, so the tools are hard dependencies, not Recommends.
                Installing shadow-arsenal-<id> therefore pulls in the whole
                profile, and APT will refuse to leave it half-installed.
    Suggests:   shadow-arsenal (the manager). Never the other way round: the
                manager must not pull tools in.

    Because the tools are Depends, removing a single tool makes APT want to
    remove the metapackage too (the profile is no longer complete). That is the
    intended contract here; a user who wants an a-la-carte selection installs
    the individual tool packages, or the Arsenal manager, instead of the
    metapackage.

Tools are never Pre-Depends, and nothing here is Essential or Priority above
optional: no tool is installed unless a user asks for a profile.
"""
import argparse
import os
import sys
import textwrap

sys.dont_write_bytecode = True

import arsenal_manifest as am

OUTPUT = os.path.join(am.ARSENAL_DIR, "packaging", "control.in")

HEADER = """\
# Generated by arsenal/tools/gen-control.py from arsenal/profiles/*.json.
# Do not edit: change the manifests and run the generator again.
# Merge into debian/control (binary package stanzas of source package shadow-os).
"""

AUTHORISED_USE = (
    "These tools are for authorised security testing, research, defence and "
    "education only: use them on systems you own or have explicit written "
    "permission to test, and follow the law that applies to you. They come "
    "with no warranty."
)

MANAGER_STANZA = """\
Package: shadow-arsenal
Architecture: any
Depends: ${shlibs:Depends}, ${misc:Depends}, shadow-ui (= ${binary:Version}),
 shadow-arsenal-data (= ${source:Version}), dpkg, apt
Recommends: packagekit, polkitd, shadow-terminal
Description: SHADOW Arsenal - security tool profile manager
 Browse the SHADOW Arsenal profiles (web, network, red team, blue team,
 forensics, reverse engineering, development), see which tools are installed
 and install or remove a whole profile or single tools through PackageKit.
 Tools that are not available from the SHADOW repositories are listed with a
 link to their official source; nothing is downloaded behind your back.
 .
 The manager installs no tools by itself.
 .
"""

DATA_STANZA = """\
Package: shadow-arsenal-data
Architecture: all
Multi-Arch: foreign
Depends: ${misc:Depends}
Description: SHADOW Arsenal - profile manifests
 Machine-readable descriptions of the SHADOW Arsenal security tool profiles:
 which Debian packages belong to a profile, what each tool is for and how it
 is started, and which well-known tools are not packaged and where their
 vendors publish them. Used by the Arsenal manager and by the
 shadow-arsenal-* metapackages.
 .
 This package contains manifests only: no tools, exploit code, payloads,
 word lists or credentials.
"""


def wrap_description(text, width=78):
    """Extended description lines (each indented by one space)."""
    lines = []
    for paragraph in text.split("\n\n"):
        if lines:
            lines.append(" .")
        lines.extend(" " + line for line in textwrap.wrap(" ".join(paragraph.split()), width - 1))
    return lines


def relation_field(name, items, width=78):
    """A folded relationship field, one item per continuation line."""
    if not items:
        return []
    lines = [f"{name}:"]
    for index, item in enumerate(items):
        lines.append(f" {item}{',' if index < len(items) - 1 else ''}")
    return lines


def tool_relation(tool):
    arches = am.tool_architectures(tool)
    if set(arches) == set(am.ARCHITECTURES):
        return tool["package"]
    return f"{tool['package']} [{' '.join(sorted(arches))}]"


def profile_stanza(profiles, ident):
    manifest = profiles[ident]
    own = sorted(am.own_tools(manifest), key=lambda tool: tool["package"])
    arch_specific = any(set(am.tool_architectures(tool)) != set(am.ARCHITECTURES) for tool in own)
    includes = manifest.get("includes", [])

    depends = ["${misc:Depends}", "shadow-arsenal-data (>= ${source:Version})"]
    depends += [f"{profiles[other]['metapackage']} (>= ${{source:Version}})" for other in includes]
    depends += [tool_relation(tool) for tool in own]

    lines = [f"Package: {manifest['metapackage']}",
             f"Architecture: {'any' if arch_specific else 'all'}",
             "Section: metapackages"]
    lines += relation_field("Depends", depends)
    lines += ["Suggests: shadow-arsenal"]
    lines.append(f"Description: SHADOW Arsenal profile - {manifest['name']}")
    count = len(am.effective_tools(profiles, ident))
    body = manifest["description"]
    if includes:
        body += (f"\n\nThis metapackage depends on the metapackages of the profiles it combines "
                 f"({count} tools in total).")
    else:
        body += (f"\n\nThis metapackage depends on the {count} tools of the profile, all from Debian main; "
                 f"APT installs every one of them with it.")
    external = am.effective_external(profiles, ident)
    if external and not includes:
        body += ("\n\nNot included, because they are not in Debian main: "
                 + ", ".join(entry["name"] for entry in external)
                 + ". The Arsenal manager lists where their vendors publish them.")
    body += "\n\n" + AUTHORISED_USE
    lines += wrap_description(body)
    return "\n".join(lines) + "\n"


def generate(profiles):
    manager = MANAGER_STANZA + "\n".join(wrap_description(AUTHORISED_USE)) + "\n"
    stanzas = [HEADER, manager, DATA_STANZA]
    stanzas += [profile_stanza(profiles, ident) for ident in profiles]
    return "\n".join(stanzas)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--profiles-dir", default=am.PROFILES_DIR)
    parser.add_argument("--output", default=OUTPUT)
    parser.add_argument("--check", action="store_true", help="only verify that the output file is current")
    parser.add_argument("--stdout", action="store_true", help="print instead of writing the file")
    args = parser.parse_args()

    try:
        profiles = am.load_profiles(args.profiles_dir)
        for ident in profiles:
            am.included_profiles(profiles, ident)
    except am.ManifestError as error:
        print(f"gen-control: {error}", file=sys.stderr)
        return 2
    text = generate(profiles)

    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        try:
            with open(args.output, encoding="utf-8") as handle:
                current = handle.read()
        except OSError:
            current = None
        if current != text:
            print(f"gen-control: {args.output} is out of date; run arsenal/tools/gen-control.py", file=sys.stderr)
            return 1
        print(f"gen-control: {args.output} is up to date")
        return 0
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"gen-control: wrote {args.output} ({len(profiles)} profile metapackages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

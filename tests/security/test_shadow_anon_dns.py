"""Hide Me (distro/base/rootfs/usr/bin/shadow-anon): DNS-over-Tor, with and
without systemd-resolved, across a restart.

    python3 tests/security/test_shadow_anon_dns.py [-v]

With systemd-resolved, DNS protection is a runtime drop-in
(/run/systemd/resolved.conf.d/95-shadow-anon.conf, which must leave Tor's
DNSPort as resolved's ONLY global server: the fake resolved merges the shipped
80-shadow-privacy.conf and the drop-ins as resolved does) plus an iptables
redirect of port 53 to Tor's DNSPort that exempts only Tor; the choice is kept
in /etc/shadow-os/hide-me.json and "boot" puts the runtime parts back. Without it (older installs) resolv.conf points at 127.0.0.1 and
NetworkManager is told to leave DNS alone. resolv.conf is never made
immutable any more.

These tests drive the real functions against a temporary directory (every
absolute path constant is pointed there, see shadow_anon_testlib) and a fake
"sh" that keeps iptables chains, the kill switch's status, systemctl calls
and NetworkManager's resolv.conf writing in memory. A restart is: all
firewall rules gone and /run emptied, files kept.

Standard library only; runs as any user, changes nothing outside the
temporary directory.
"""

"""Hide Me (distro/base/rootfs/usr/bin/shadow-anon): DNS-over-Tor across a
restart.

    python3 tests/security/test_shadow_anon_dns.py [-v]

DNS protection keeps files that survive a restart (resolv.conf locked to
127.0.0.1, NetworkManager told to leave DNS alone) and an iptables redirect
to Tor's DNSPort that does not. These tests drive the real functions against
a temporary directory (every path constant is pointed there) and a fake
"sh" that keeps iptables chains, systemctl calls and NetworkManager's
resolv.conf writing in memory. A restart is: all firewall rules gone and
/run emptied, files kept.

Standard library only; runs as any user, changes nothing outside the
temporary directory.
"""
import importlib.machinery
import importlib.util
import io
import json
import os
import shutil
import sys
import tempfile
import unittest
from contextlib import redirect_stdout
from unittest import mock

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
TOOL = os.path.join(ROOT, "distro", "base", "rootfs", "usr", "bin", "shadow-anon")
UNIT = os.path.join(ROOT, "distro", "base", "rootfs", "usr", "lib", "systemd", "system", "shadow-anon-boot.service")
NM_TEXT = "# Generated by NetworkManager\nnameserver 192.168.1.1\n"


def load_tool():
    sys.dont_write_bytecode = True
    loader = importlib.machinery.SourceFileLoader("shadow_anon", TOOL)
    spec = importlib.util.spec_from_loader(loader.name, loader)
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


class FakeSystem:
    """iptables, systemctl, chattr, nmcli and rfkill, in memory."""

    def __init__(self, tool):
        self.tool = tool
        self.calls = []
        self.tables = {"filter": {}, "nat": {}}   # chain -> [rule]
        self.hooks = {"filter": [], "nat": []}    # chains OUTPUT jumps to
        self.immutable = False
        self.nm_writes = True                     # does NetworkManager write resolv.conf?

    def restart(self):
        """A restart: firewall rules are gone, /run is empty, files stay."""
        self.tables = {"filter": {}, "nat": {}}
        self.hooks = {"filter": [], "nat": []}
        for p in (self.tool.STATE_FILE, self.tool.NM_RESOLV):
            if os.path.exists(p):
                os.unlink(p)

    def nm_rewrite(self):
        t = self.tool
        if not self.nm_writes or os.path.exists(t.NM_DNS_CONF) or self.immutable:
            return
        if os.path.islink(t.RESOLV):
            return                      # rc-manager "symlink": leaves links alone
        os.makedirs(os.path.dirname(t.NM_RESOLV), exist_ok=True)
        with open(t.NM_RESOLV, "w") as f:
            f.write(NM_TEXT)
        with open(t.RESOLV, "w") as f:
            f.write(NM_TEXT)

    def __call__(self, cmd, timeout=30):
        self.calls.append(list(cmd))
        prog, args = cmd[0], list(cmd[1:])
        if prog in ("iptables", "ip6tables"):
            return self.iptables(prog, args)
        if prog == "systemctl":
            if args[:2] == ["reload", "NetworkManager"]:
                self.nm_rewrite()
            return 0, "", ""
        if prog == "nmcli":
            if args[:2] == ["general", "reload"]:
                self.nm_rewrite()
            return 0, "", ""
        if prog == "chattr":
            if args[0] == "+i":
                self.immutable = True
            elif args[0] == "-i":
                self.immutable = False
            return 0, "", ""
        if prog == "rfkill":
            return 0, "0: hci0: Bluetooth\n\tSoft blocked: no\n\tHard blocked: no", ""
        return 0, "", ""

    def iptables(self, prog, a):
        if prog == "ip6tables":
            return 0, "", ""
        table = "filter"
        if a[:1] == ["-t"]:
            table, a = a[1], a[2:]
        chains, hooks = self.tables[table], self.hooks[table]
        op = a[0]
        if op == "-N":
            if a[1] in chains:
                return 1, "", "Chain already exists."
            chains[a[1]] = []
            return 0, "", ""
        if op == "-F":
            if a[1] not in chains:
                return 1, "", "No chain"
            chains[a[1]] = []
            return 0, "", ""
        if op == "-X":
            if a[1] in chains and a[1] not in hooks:
                del chains[a[1]]
                return 0, "", ""
            return 1, "", ""
        if op == "-A":
            if a[1] == "OUTPUT":
                hooks.append(a[-1])
            elif a[1] in chains:
                chains[a[1]].append(" ".join(a[2:]))
            else:
                return 1, "", "No chain"
            return 0, "", ""
        if op == "-I" and a[1] == "OUTPUT":
            hooks.insert(0, a[-1])
            return 0, "", ""
        if op == "-C" and a[1] == "OUTPUT":
            return (0, "", "") if a[-1] in hooks else (1, "", "")
        if op == "-D" and a[1] == "OUTPUT":
            if a[-1] in hooks:
                hooks.remove(a[-1])
                return 0, "", ""
            return 1, "", ""
        if op == "-S" and a[1] == "OUTPUT":
            return 0, "\n".join(["-P OUTPUT ACCEPT"] + [f"-A OUTPUT -j {h}" for h in hooks]), ""
        if op == "-L":
            if a[1] not in chains:
                return 1, "", "No chain"
            return 0, "\n".join(chains[a[1]]), ""
        raise AssertionError(f"fake iptables: unhandled {a}")


class DnsAcrossRestart(unittest.TestCase):
    def setUp(self):
        self.tool = load_tool()
        self.dir = tempfile.mkdtemp(prefix="shadow-anon-test-")
        t = self.tool

        def p(rel):
            path = os.path.join(self.dir, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            return path

        t.RESOLV = p("etc/resolv.conf")
        t.RESOLV_BACKUP = p("etc/resolv.conf.shadow-backup")
        t.NM_DNS_CONF = p("etc/NetworkManager/conf.d/90-shadow-dns.conf")
        t.NM_RESOLV = p("run/NetworkManager/resolv.conf")
        t.TORRC_D = p("etc/tor/torrc.d/x")[:-2]
        t.TORRC = p("etc/tor/torrc")
        t.TPROXY_CF = os.path.join(t.TORRC_D, "shadow-tproxy.conf")
        t.TORDNS_CF = os.path.join(t.TORRC_D, "shadow-dns.conf")
        t.BRIDGE_CF = os.path.join(t.TORRC_D, "shadow-bridges.conf")
        t.STATE_FILE = p("run/shadow-anon-state.json")
        t.SYSCTL_FILE = p("etc/sysctl.d/90-shadow-anon.conf")
        t.USB_RULE = p("etc/udev/rules.d/90-shadow-nousb.rules")
        with open(t.RESOLV, "w") as f:
            f.write(NM_TEXT)
        self.fake = FakeSystem(t)
        self.tor_installed = True
        self.patches = [
            mock.patch.object(t, "sh", self.fake),
            mock.patch.object(t, "need_root", lambda: None),
            mock.patch.object(t, "have", lambda prog: prog != "tor" or self.tor_installed),
            mock.patch.object(t.time, "sleep", lambda s: None),
        ]
        for pt in self.patches:
            pt.start()
        self.out = io.StringIO()

    def tearDown(self):
        for pt in self.patches:
            pt.stop()
        shutil.rmtree(self.dir, ignore_errors=True)

    # helpers
    def run_tool(self, fn, *args):
        with redirect_stdout(self.out):
            return fn(*args)

    def state(self):
        with open(self.tool.STATE_FILE) as f:
            return json.load(f)

    def resolv(self):
        with open(self.tool.RESOLV) as f:
            return f.read()

    def protect_then_restart(self):
        self.run_tool(self.tool.dns_protect_on)
        self.assertTrue(self.tool.tor_dns_redirect_active())
        self.assertIn("DNS routed through Tor", self.resolv())
        self.assertTrue(self.fake.immutable)
        self.fake.restart()
        # This is the bug: after a restart the files still point DNS at Tor,
        # but nothing sends port 53 to Tor's DNSPort any more.
        self.assertTrue(self.tool.dns_protection_configured())
        self.assertFalse(self.tool.tor_dns_redirect_active())

    # tests
    def test_boot_puts_the_redirect_back(self):
        self.protect_then_restart()
        self.run_tool(self.tool.boot)
        self.assertTrue(self.tool.tor_dns_redirect_active())
        self.assertIn("DNS routed through Tor", self.resolv())
        self.assertTrue(os.path.exists(self.tool.NM_DNS_CONF))
        self.assertIn(["systemctl", "start", "--no-block", "tor@default"], self.fake.calls)
        self.assertTrue(self.state()["dns_protected"])

    def test_redirect_exempts_tor_once_and_hooks_once(self):
        self.protect_then_restart()
        self.run_tool(self.tool.boot)
        self.run_tool(self.tool.boot)
        self.assertEqual(self.fake.hooks["nat"].count("SHADOWDNS"), 1)
        rules = self.fake.tables["nat"]["SHADOWDNS"]
        self.assertEqual(sum("debian-tor" in r for r in rules), 1)
        self.assertEqual(sum("--to-ports 5353" in r for r in rules), 2)

    def test_boot_without_tor_hands_dns_back(self):
        self.protect_then_restart()
        self.tor_installed = False
        self.run_tool(self.tool.boot)
        self.assertFalse(os.path.exists(self.tool.NM_DNS_CONF))
        self.assertEqual(self.resolv(), NM_TEXT)
        self.assertFalse(self.fake.immutable)
        self.assertFalse(self.tool.tor_dns_redirect_active())
        self.assertFalse(self.state()["dns_protected"])

    def test_boot_writes_a_missing_tor_dns_config(self):
        self.protect_then_restart()
        os.unlink(self.tool.TORDNS_CF)
        self.run_tool(self.tool.boot)
        with open(self.tool.TORDNS_CF) as f:
            self.assertIn("DNSPort 127.0.0.1:5353", f.read())
        self.assertIn(["systemctl", "reload-or-restart", "--no-block", "tor@default"], self.fake.calls)
        self.assertTrue(self.tool.tor_dns_redirect_active())

    def test_boot_without_protection_changes_nothing(self):
        self.run_tool(self.tool.boot)
        self.assertEqual(self.resolv(), NM_TEXT)
        self.assertEqual(self.fake.hooks, {"filter": [], "nat": []})
        self.assertFalse([c for c in self.fake.calls if c[0] in ("systemctl", "chattr", "nmcli")])
        st = self.state()
        self.assertFalse(st["dns_protected"] or st["transparent_proxy"] or st["kill_switch"] or st["ghost_mode"])

    def test_state_after_restart_is_the_truth(self):
        # Ghost Mode before the restart: its rules end with it, DNS stays.
        with open(self.tool.STATE_FILE, "w") as f:
            json.dump({"ghost_mode": True, "threat_model": "maximum", "transparent_proxy": True,
                       "kill_switch": True, "dns_protected": True}, f)
        self.run_tool(self.tool.dns_protect_on)
        st_before = self.tool.load_state()
        self.assertTrue(st_before["ghost_mode"])
        self.fake.restart()
        with open(self.tool.STATE_FILE, "w") as f:    # even if /run had survived
            json.dump(st_before, f)
        self.run_tool(self.tool.boot)
        st = self.state()
        self.assertFalse(st["ghost_mode"])
        self.assertFalse(st["transparent_proxy"])
        self.assertFalse(st["kill_switch"])
        self.assertTrue(st["dns_protected"])
        self.assertEqual(st["threat_model"], "enhanced")

    def test_boot_while_ghost_mode_runs_keeps_it(self):
        # The package runs "boot" on upgrade: rules active now must stay and be reported.
        t = self.tool
        self.fake.tables["nat"]["SHADOWTOR"] = ["-p tcp --syn -j REDIRECT --to-ports 9040"]
        self.fake.hooks["nat"].append("SHADOWTOR")
        self.fake.tables["filter"]["SHADOWKILL"] = ["-j DROP"]
        self.fake.hooks["filter"].append("SHADOWKILL")
        with open(t.STATE_FILE, "w") as f:
            json.dump({"ghost_mode": True, "threat_model": "maximum"}, f)
        with open(t.RESOLV, "w") as f:
            f.write(t.RESOLV_TOR)
        with open(t.NM_DNS_CONF, "w") as f:
            f.write("[main]\ndns=none\n")
        os.makedirs(t.TORRC_D, exist_ok=True)
        with open(t.TORDNS_CF, "w") as f:
            f.write("DNSPort 127.0.0.1:5353\n")
        self.run_tool(t.boot)
        st = self.state()
        self.assertTrue(st["ghost_mode"] and st["transparent_proxy"] and st["kill_switch"] and st["dns_protected"])
        self.assertEqual(st["threat_model"], "maximum")
        self.assertEqual(self.fake.hooks["nat"], ["SHADOWTOR"])   # the proxy already sends DNS to Tor

    def test_off_after_restart_uses_networkmanager_not_a_stale_copy(self):
        with open(self.tool.RESOLV_BACKUP, "w") as f:   # left by an older version
            f.write("nameserver 10.99.99.99\n")
        self.protect_then_restart()
        self.run_tool(self.tool.dns_protect_off)
        self.assertEqual(self.resolv(), NM_TEXT)
        self.assertFalse(os.path.exists(self.tool.RESOLV_BACKUP))
        self.assertFalse(os.path.exists(self.tool.NM_DNS_CONF))
        self.assertFalse(self.fake.immutable)
        chattr = self.fake.calls.index(["chattr", "-i", self.tool.RESOLV])
        reload = max(i for i, c in enumerate(self.fake.calls) if c[:3] == ["nmcli", "general", "reload"])
        self.assertLess(chattr, reload)

    def test_off_when_networkmanager_writes_nothing(self):
        self.protect_then_restart()
        self.fake.nm_writes = False
        self.run_tool(self.tool.dns_protect_off)
        txt = self.resolv()
        self.assertIn("nameserver 9.9.9.9", txt)
        self.assertNotIn("Tor", txt)

    def test_off_links_networkmanagers_file_when_only_that_exists(self):
        self.protect_then_restart()
        self.fake.nm_writes = False
        with open(self.tool.NM_RESOLV, "w") as f:
            f.write(NM_TEXT)
        self.run_tool(self.tool.dns_protect_off)
        self.assertTrue(os.path.islink(self.tool.RESOLV))
        self.assertEqual(os.readlink(self.tool.RESOLV), self.tool.NM_RESOLV)

    def test_proxy_off_after_restart_keeps_dns_protections_tor_config(self):
        self.protect_then_restart()
        with mock.patch.object(self.tool, "restart_tor", lambda: True):
            self.run_tool(self.tool.transparent_proxy_off)
        self.assertTrue(os.path.exists(self.tool.TORDNS_CF))

    def test_boot_unit(self):
        with open(UNIT) as f:
            unit = f.read()
        self.assertIn("ExecStart=/usr/bin/shadow-anon boot", unit)
        self.assertIn("Type=oneshot", unit)
        self.assertIn("Before=network-pre.target", unit)
        self.assertIn("WantedBy=multi-user.target", unit)
        with open(os.path.join(ROOT, "debian", "shadow-hardening.install")) as f:
            self.assertIn("shadow-anon-boot.service", f.read())
        with open(os.path.join(ROOT, "debian", "rules")) as f:
            rules = f.read()
        self.assertIn("dh_installsystemd -pshadow-hardening shadow-anon-boot.service", rules)
        self.assertIn("--no-enable --no-start shadow-anon-rotate.service shadow-anon-rotate.timer", rules)


if __name__ == "__main__":
    unittest.main()

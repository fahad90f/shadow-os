    def test_localhost_9050_over_ipv6_is_refused_not_left_to_a_user(self):
        """Regression (d3-02): SHADOWSOCKS was IPv4 only. Clients that name
        the proxy "localhost:9050" (curl --socks5-hostname, PySocks as
        requests uses it, ALL_PROXY=socks5h://localhost:9050) try ::1 first
        ("::1 localhost" in /etc/hosts; RFC 6724 puts it before 127.0.0.1)
        and reach 127.0.0.1:9050 only when ::1 refuses, so a user who bound
        [::1]:9050 or [::]:9050 got every name and connection. Its IPv6 side
        sends [::1]:9050 to a closed port (1, only root may bind it): refused,
        and the client moves on to 127.0.0.1:9050, i.e. Tor."""
        t = self.tool
        v6 = self.fake.tables["v6"]["nat"]
        self.run_tool(t.boot)
        self.assertEqual(v6["chains"]["SHADOWSOCKS"], ["-d ::1/128 -p tcp --dport 9050 -j REDIRECT --to-ports 1"])
        self.assertEqual(v6["chains"]["SHADOWSOCKS"], [" ".join(r) for r in t.socks6_rules()])
        self.assertEqual(v6["hooks"], ["SHADOWSOCKS"])
        self.assertEqual(self.fake.nat("SHADOWSOCKS"), [" ".join(r) for r in t.socks_rules()])
        self.assertTrue(t.socks_redirect_active())
        self.assertIsNone(self.state()["error"])
        self.assertIn("to [::1]:9050 are refused", self.out.getvalue())
        # An older version's chain (IPv4 only), or a lost IPv6 hook, is not in
        # place: boot adds the IPv6 side and leaves the IPv4 side alone (it
        # is never emptied: 127.0.0.1:9050 is never left free).
        for broken in ("no chain", "no hook", "wrong rule"):
            with self.subTest(broken=broken):
                if broken == "no chain":
                    v6["hooks"].remove("SHADOWSOCKS")
                    del v6["chains"]["SHADOWSOCKS"]
                elif broken == "no hook":
                    v6["hooks"].remove("SHADOWSOCKS")
                else:
                    v6["chains"]["SHADOWSOCKS"] = ["-d ::1/128 -p tcp --dport 9050 -j RETURN"]
                self.assertFalse(t.socks_redirect_active())
                self.fake.calls.clear()
                self.run_tool(t.boot)
                self.assertTrue(t.socks_redirect_active())
                self.assertEqual(v6["chains"]["SHADOWSOCKS"], [" ".join(r) for r in t.socks6_rules()])
                self.assertEqual(v6["hooks"], ["SHADOWSOCKS"])
                self.assertFalse([c for c in self.fake.calls if c[0] == "iptables" and "SHADOWSOCKS" in c
                                  and not {"-S", "-L"} & set(c)])
        # A refused IPv6 rule is recorded; the IPv4 side stays (it protects
        # 127.0.0.1:9050 on its own).
        real = self.fake.iptables

        def failing(prog, a):
            if prog == "ip6tables" and "SHADOWSOCKS" in a and "REDIRECT" in a:
                return 1, "", "ip6tables: refused"
            return real(prog, a)
        self.fake.iptables = failing
        v6["hooks"].remove("SHADOWSOCKS")
        with redirect_stdout(self.out), mock.patch("sys.stderr", io.StringIO()):
            self.assertEqual(t.main(["boot"]), 3)
        self.assertIn("ip6tables refused a rule of SHADOWSOCKS", self.state()["error"])
        self.assertEqual(self.fake.hooks["nat"], ["SHADOWSOCKS"])
        self.assertEqual(self.fake.nat("SHADOWSOCKS"), [" ".join(r) for r in t.socks_rules()])
        self.assertNotIn("SHADOWSOCKS", v6["hooks"])
        self.fake.iptables = real
        # ipv6.disable=1: no IPv6 side, and none is needed.
        self.fake.tables = {"v4": self.fake._empty(), "v6": self.fake._empty()}
        shutil.rmtree(os.path.dirname(t.PROC_IPV6_CONF))
        self.fake.calls.clear()
        self.run_tool(t.boot)
        self.assertFalse([c for c in self.fake.calls if c[0] == "ip6tables" and "SHADOWSOCKS" in c])
        self.assertTrue(t.socks_redirect_active())
        self.assertIsNone(self.state()["error"])


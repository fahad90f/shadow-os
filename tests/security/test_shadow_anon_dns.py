    def test_boot_moves_dns_over_tor_off_the_port_any_user_could_bind(self):
        """Regression (upgrade): DNS-over-Tor as the previous version set it
        up, with Tor's DNSPort on UDP 127.0.0.1:5353, where any user's socket
        with SO_REUSEADDR co-binds with Tor's and gets every query. "boot"
        (run on upgrade) rewrites Tor's file, the redirect and resolved's
        drop-in for the privileged port, and restarts Tor only after them
        (and never reloads it: KeepBindCapabilities cannot change on a reload)."""
        t = self.tool
        old_tor = ("# Shadow OS DNS-over-Tor — written by shadow-anon\nDNSPort 127.0.0.1:5353\n"
                   "AutomapHostsOnResolve 1\nVirtualAddrNetworkIPv4 10.192.0.0/10\n")
        old_rules = ["-m owner --uid-owner debian-tor -j RETURN",
                     "-m owner --uid-owner systemd-resolve -p tcp --dport 853 -j REDIRECT --to-ports 1",
                     "-m owner --uid-owner systemd-resolve -p tcp -d 127.0.0.1 --dport 5353 -j REDIRECT --to-ports 1",
                     "-p udp --dport 53 -j REDIRECT --to-ports 5353", "-p tcp --dport 53 -j REDIRECT --to-ports 1"]
        self.run_tool(t.dns_protect_on)
        with open(t.TORDNS_CF, "w") as f:
            f.write(old_tor)
        with open(t.RESOLVED_DROPIN, "w") as f:
            f.write(t.RESOLVED_DROPIN_TEXT.replace("127.0.0.1:26", "127.0.0.1:5353"))
        self.fake.resolved_start()
        self.fake.tables["v4"]["nat"]["chains"]["SHADOWDNS"] = list(old_rules)
        self.assertEqual(self.fake.resolved_servers, ["127.0.0.1:5353"])
        self.assertTrue(t._chain_outdated("SHADOWDNS"))
        self.assertFalse(t._sends_tcp_to_dns_port("SHADOWDNS"))   # not caught by the earlier TCP check
        self.assertFalse(t.dns_protection_active())               # resolved asks the old port
        order = []
        real = self.fake.__call__

        def spy(cmd, timeout=30):
            if cmd[:2] == ["systemctl", "restart"] and cmd[-1] == "tor@default":
                order.append(("tor restart", self.fake.nat("SHADOWDNS") == [" ".join(r) for r in t.dns_rules()],
                              self.dropin() == DROPIN_TEXT_LINES))
            return real(cmd, timeout)
        self.fake.calls.clear()
        with mock.patch.object(t, "sh", spy):
            self.run_tool(t.boot)
        with open(t.TORDNS_CF) as f:
            self.assertEqual(f.read(), t._tor_dns_text())
        self.assertEqual(self.dropin(), DROPIN_TEXT_LINES)
        self.assertEqual(self.fake.nat("SHADOWDNS"), [" ".join(r) for r in t.dns_rules()])
        self.assertEqual(self.fake.resolved_servers, TOR_ONLY)
        self.assertEqual(order, [("tor restart", True, True)])     # once, after the rules and the drop-in
        # A running system (an upgrade): the restart is waited for, so the
        # state below is the truth (d1-04: it was only queued, unchecked).
        self.assertIn(["systemctl", "restart", "tor@default"], self.fake.calls)
        self.assertNotIn(["systemctl", "restart", "--no-block", "tor@default"], self.fake.calls)
        self.assertTrue(self.state()["dns_protected"])
        self.assertIsNone(self.state()["error"])
        # The next boot leaves the running Tor alone (no start, no restart).
        self.fake.calls.clear()

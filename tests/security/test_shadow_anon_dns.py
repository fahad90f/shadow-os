class FakeSystem:
    """iptables/ip6tables, systemctl, chattr, nmcli, rfkill, shadow-killswitch and
    systemd-resolved's global server list ("resolvectl dns"), in memory. resolved
    takes its servers from the files (shipped 80 file + drop-ins under root, merged
    as resolved does) when it (re)starts, not when a file is written."""

    def __init__(self, tool, root=None):
        self.tool = tool
        self.root = root
        self.resolved_servers = None              # None: resolved not running
        self.calls = []
        self.tables = {"v4": self._empty(), "v6": self._empty()}
        self.immutable = False
        self.nm_writes = True                     # does NetworkManager write resolv.conf?
        self.resolved_enabled = False
        self.fail_resolved_restart = False
        self.tor_active = True                    # tor@default
        self.fail_tor_restart = False             # "systemctl restart tor@default" fails (Tor exits)
        # "systemctl is-system-running": a running system (an upgrade, boot by
        # hand) until restart(), which stands for a start: "starting".
        self.system_state = "running"
        self.ks = {"mode": "off", "active": False, "loaded": False, "lan": False, "persistent_mode": "off",
                   "runtime_override": False, "escape_hatch": False, "error": None}

    @staticmethod
    def _empty():
        return {"filter": {"chains": {}, "hooks": []}, "nat": {"chains": {}, "hooks": []}}

    @property
    def hooks(self):
        return {t: list(v["hooks"]) for t, v in self.tables["v4"].items()}

    def nat(self, chain):
        return self.tables["v4"]["nat"]["chains"].get(chain)

    def restart(self):
        """A restart: firewall rules are gone, /run is empty, files stay."""
        self.tables = {"v4": self._empty(), "v6": self._empty()}
        t = self.tool
        for p in (t.STATE_FILE, t.NM_RESOLV, t.RESOLVED_DROPIN, t.MAC_SALT):
            if os.path.exists(p):
                os.unlink(p)
        self.ks.update(mode=self.ks["persistent_mode"], runtime_override=False)
        self.ks.update(active=self.ks["mode"] != "off", loaded=self.ks["mode"] != "off")
        self.resolved_start()
        self.tor_active = False                   # tor@default starts after the network, i.e. after "boot"
        self.system_state = "starting"            # "boot" runs while systemd starts the system

    def resolved_start(self):
        self.resolved_servers = lib.resolved_global_dns(self.root) if self.resolved_enabled else None

    def nm_rewrite(self):
        t = self.tool
        if not self.nm_writes or os.path.exists(t.NM_DNS_CONF) or self.immutable:
            return
        if os.path.islink(t.RESOLV):
            return                      # rc-manager "symlink": leaves links alone
        os.makedirs(os.path.dirname(t.NM_RESOLV), exist_ok=True)
        with open(t.NM_RESOLV, "w") as f:
            f.write(NM_TEXT)
        with open(t.RESOLV, "w") as f:
            f.write(NM_TEXT)

    def __call__(self, cmd, timeout=30):
        self.calls.append(list(cmd))
        prog, args = cmd[0], list(cmd[1:])
        if prog in ("iptables", "ip6tables"):
            return self.iptables(prog, args)
        if prog == "shadow-killswitch":
            return self.killswitch(args)
        if prog == "systemctl":
            if args[:2] == ["reload", "NetworkManager"]:
                self.nm_rewrite()
            if args[0] == "is-enabled" and args[-1] == "systemd-resolved.service":
                return (0, "", "") if self.resolved_enabled else (1, "", "")
            if args[0] == "is-active":
                return (0, "", "") if args[-1] == "tor@default" and self.tor_active else (3, "", "")
            if args == ["is-system-running"]:
                return (0 if self.system_state == "running" else 1), self.system_state, ""
            if args[0] in ("start", "restart") and args[-1] == "tor@default" and "--no-block" in args:
                return 0, "", ""                  # queued: at start-up Tor waits for the network
            if args[0] in ("start", "restart") and args[-1] == "tor@default":
                if args[0] == "restart" or not self.tor_active:
                    self.tor_active = not self.fail_tor_restart
                if self.fail_tor_restart:
                    return 1, "", "Job for tor@default.service failed because the control process exited."
            if args[0] == "restart" and args[-1] == "systemd-resolved.service":
                if self.fail_resolved_restart:
                    return 1, "", "Job for systemd-resolved.service failed."
                self.resolved_start()
            return 0, "", ""
        if prog == "resolvectl" and args == ["dns"]:
            if self.resolved_servers is None:
                return 1, "", "Failed to get global data: Unit dbus-org.freedesktop.resolve1.service not found."
            return 0, f"Global: {' '.join(self.resolved_servers)}\nLink 2 (eth0): 192.0.2.1", ""
        if prog == "nmcli":
            if args[:2] == ["general", "reload"]:
                self.nm_rewrite()
            return 0, "", ""
        if prog == "chattr":
            if args[0] == "+i":
                self.immutable = True
            elif args[0] == "-i":
                self.immutable = False
            return 0, "", ""
        if prog == "rfkill":
            return 0, "0: hci0: Bluetooth\n\tSoft blocked: no\n\tHard blocked: no", ""
        return 0, "", ""

    def killswitch(self, a):
        if a[:2] == ["status", "--json"]:
            return (3 if self.ks["error"] else 0), json.dumps(self.ks), ""
        if a[:1] == ["set"]:
            mode = a[1]
            lan = True if "--lan" in a else False if "--no-lan" in a else self.ks["lan"]
            self.ks.update(mode=mode, lan=lan, active=mode != "off", loaded=mode != "off", error=None,
                           runtime_override="--runtime" in a, escape_hatch=False)
            if "--runtime" not in a:
                self.ks["persistent_mode"] = mode
            return 0, "", ""
        return 2, "", "fake shadow-killswitch: unhandled"

    def iptables(self, prog, a):
        fam = "v6" if prog == "ip6tables" else "v4"
        table = "filter"
        if a[:1] == ["-t"]:
            table, a = a[1], a[2:]
        chains, hooks = self.tables[fam][table]["chains"], self.tables[fam][table]["hooks"]
        op = a[0]
        if op == "-N":
            if a[1] in chains:
                return 1, "", "Chain already exists."
            chains[a[1]] = []
            return 0, "", ""
        if op == "-F":
            if a[1] not in chains:
                return 1, "", "No chain"
            chains[a[1]] = []
            return 0, "", ""
        if op == "-X":
            if a[1] in chains and a[1] not in hooks:
                del chains[a[1]]
                return 0, "", ""
            return 1, "", ""
        if op == "-A":
            if a[1] == "OUTPUT":
                hooks.append(a[-1])
            elif a[1] in chains:
                chains[a[1]].append(" ".join(a[2:]))
            else:
                return 1, "", "No chain"
            return 0, "", ""
        if op == "-I" and a[1] == "OUTPUT":
            hooks.insert(0, a[-1])
            return 0, "", ""
        if op == "-C" and a[1] == "OUTPUT":
            return (0, "", "") if a[-1] in hooks else (1, "", "")
        if op == "-D" and a[1] == "OUTPUT":
            if a[-1] in hooks:
                hooks.remove(a[-1])
                return 0, "", ""
            return 1, "", ""
        if op == "-S" and a[1] == "OUTPUT":
            return 0, "\n".join(["-P OUTPUT ACCEPT"] + [f"-A OUTPUT -j {h}" for h in hooks]), ""
        if op == "-S":
            if a[1] not in chains:
                return 1, "", "iptables: No chain/target/match by that name."
            return 0, "\n".join([f"-N {a[1]}"] + [f"-A {a[1]} {r}" for r in chains[a[1]]]), ""
        if op == "-L":
            if a[1] not in chains:
                return 1, "", "No chain"
            return 0, "\n".join(chains[a[1]]), ""
        raise AssertionError(f"fake iptables: unhandled {a}")


class HideMeDnsBase(unittest.TestCase):
    resolved = False

    def setUp(self):
        self.tool = load = lib.load_tool()
        self.dir = tempfile.mkdtemp(prefix="shadow-anon-test-")
        lib.redirect_paths(load, self.dir)
        t = self.tool
        with open(t.RESOLV, "w") as f:
            f.write(NM_TEXT)
        self.fake = FakeSystem(t, self.dir)
        self.fake.resolved_enabled = self.resolved
        self.fake.resolved_start()
        if self.resolved:
            os.unlink(t.RESOLV)
            os.symlink(t.STUB_TARGET, t.RESOLV)
            with open(t.RESOLVED_DAEMON, "w") as f:
                f.write("")
        self.tor_installed = True
        self.patches = [
            mock.patch.object(t, "sh", self.fake),
            mock.patch.object(t, "need_root", lambda: None),
            mock.patch.object(t, "have", lambda prog: prog != "tor" or self.tor_installed),
            mock.patch.object(t, "user_exists", lambda name: True),
            mock.patch.object(t.time, "sleep", lambda s: None),
        ]
        for pt in self.patches:
            pt.start()
        self.out = io.StringIO()

    def tearDown(self):
        for pt in self.patches:
            pt.stop()
        shutil.rmtree(self.dir, ignore_errors=True)

    # helpers
    def run_tool(self, fn, *args):
        lib.check_redirected(self.tool, self.dir)
        with redirect_stdout(self.out):
            return fn(*args)

    def state(self):
        with open(self.tool.STATE_FILE) as f:
            return json.load(f)

    def resolv(self):
        with open(self.tool.RESOLV) as f:
            return f.read()

    def cmdline(self, text):
        with open(self.tool.CMDLINE, "w") as f:
            f.write(text + "\n")


class DnsAcrossRestart(HideMeDnsBase):
    """Systems without systemd-resolved (older installs): the resolv.conf method."""

    def protect_then_restart(self):
        self.run_tool(self.tool.dns_protect_on)
        self.assertTrue(self.tool.tor_dns_redirect_active())
        self.assertIn("DNS routed through Tor", self.resolv())
        self.assertFalse(self.fake.immutable)          # never chattr +i any more
        self.fake.restart()
        # This is the bug: after a restart the files still point DNS at Tor,
        # but nothing sends port 53 to Tor's DNSPort any more.
        self.assertTrue(self.tool.dns_protection_configured())
        self.assertFalse(self.tool.tor_dns_redirect_active())

    # tests
    def test_protection_never_makes_resolv_conf_immutable(self):
        self.run_tool(self.tool.dns_protect_on)
        self.assertNotIn(["chattr", "+i", self.tool.RESOLV], self.fake.calls)
        self.assertEqual(self.state()["dns_method"], "resolv.conf")
        self.assertFalse(os.path.exists(self.tool.RESOLVED_DROPIN))

    def test_boot_puts_the_redirect_back(self):
        self.protect_then_restart()
        self.run_tool(self.tool.boot)
        self.assertTrue(self.tool.tor_dns_redirect_active())
        self.assertIn("DNS routed through Tor", self.resolv())
        self.assertTrue(os.path.exists(self.tool.NM_DNS_CONF))
        self.assertIn(["systemctl", "start", "--no-block", "tor@default"], self.fake.calls)
        self.assertTrue(self.state()["dns_protected"])

    def test_redirect_exempts_only_tor_and_hooks_once(self):
        self.protect_then_restart()
        self.run_tool(self.tool.boot)
        self.run_tool(self.tool.boot)
        self.assertEqual(self.fake.hooks["nat"].count("SHADOWDNS"), 1)
        rules = self.fake.nat("SHADOWDNS")
        self.assertEqual(rules[0], "-m owner --uid-owner debian-tor -j RETURN")   # the only exemption
        self.assertEqual(sum(r.endswith("-j RETURN") for r in rules), 1)
        # systemd-resolved is not exempt: its port-53 queries to a network's own
        # server go to Tor too. Its TCP (DNS-over-TLS to such a server, TCP to
        # Tor's DNSPort) and everyone's TCP port 53 are refused: sent to port 1,
        # which only root may bind, never to Tor's DNSPort, which has no TCP.
        self.assertEqual([r for r in rules if "systemd-resolve" in r],
                         ["-m owner --uid-owner systemd-resolve -p tcp --dport 853 -j REDIRECT --to-ports 1",
                          "-m owner --uid-owner systemd-resolve -p tcp -d 127.0.0.1 --dport 26 "
                          "-j REDIRECT --to-ports 1"])
        self.assertEqual(rules[-2:], ["-p udp --dport 53 -j REDIRECT --to-ports 26",
                                      "-p tcp --dport 53 -j REDIRECT --to-ports 1"])

    def test_no_tcp_is_sent_to_the_dnsport(self):
        """Regression: Tor's DNSPort has no TCP and 5353 is not a privileged
        port, so whoever listened on TCP 127.0.0.1:5353 got resolved's
        DNS-over-TLS (no certificate check in opportunistic mode) and every
        TCP DNS query, and its answers were used system-wide."""
        self.run_tool(self.tool.dns_protect_on)
        rules = self.fake.nat("SHADOWDNS")
        self.assertTrue(rules)
        for rule in rules:
            if "-p tcp" in rule:
                self.assertTrue(rule.endswith("-j REDIRECT --to-ports 1"), rule)
            elif "--to-ports" in rule:
                self.assertTrue(rule.startswith("-p udp "), rule)
        self.assertFalse(self.tool._sends_tcp_to_dns_port("SHADOWDNS"))
        self.assertLess(int(self.tool.CLOSED_PORT), 53)          # privileged even where the limit is lowered

    def test_tors_ports_are_privileged(self):
        """Regression: Tor's DNSPort was UDP 127.0.0.1:5353. Tor sets
        SO_REUSEADDR on it, so any user's socket with SO_REUSEADDR bound the
        same address next to Tor's and got every redirected query (and
        resolved's own) while Tor ran, and answered them; and whoever bound
        5353 or the TransPort 9040 while Tor restarted kept it. Both are now
        below 53: binding them needs CAP_NET_BIND_SERVICE, SO_REUSEADDR or
        not. Tor keeps that capability for reloads (KeepBindCapabilities 1)."""
        t = self.tool
        for port in (t.DNS_PORT, t.TPROXY_PORT):
            self.assertLess(int(port), 53)
            self.assertNotIn(port, ("53", t.CLOSED_PORT))
        self.assertNotEqual(t.DNS_PORT, t.TPROXY_PORT)
        self.run_tool(t.dns_protect_on)
        with open(t.TORDNS_CF) as f:
            text = f.read()
        self.assertIn("DNSPort 127.0.0.1:26\n", text)
        self.assertIn("KeepBindCapabilities 1\n", text)
        self.assertIn(["systemctl", "restart", "tor@default"], self.fake.calls)   # never a reload
        self.assertNotIn(["systemctl", "restart", "tor"], self.fake.calls)
        rules = self.fake.nat("SHADOWDNS")
        self.assertIn("-p udp --dport 53 -j REDIRECT --to-ports 26", rules)
        self.assertFalse([r for r in rules if "5353" in r])

    def test_a_tor_that_does_not_start_is_reported(self):
        """Regression: when "systemctl restart tor@default" failed, Hide Me
        restarted Debian's tor.service, a oneshot running /bin/true, and took
        its success for Tor's: DNS protection was reported on while Tor did
        not run (and in Ghost Mode a user who held Tor's port kept it)."""
        t = self.tool
        self.fake.fail_tor_restart = True
        with self.assertRaises(t.Failure) as cm:
            self.run_tool(t.dns_protect_on)
        self.assertIn("Tor did not start", str(cm.exception))
        self.assertNotIn(["systemctl", "restart", "tor"], self.fake.calls)
        self.assertFalse(t.tor_dns_redirect_active())
        self.assertNotIn("DNS routed through Tor", self.resolv())

    def test_boot_replaces_rules_that_send_tcp_to_the_dnsport(self):
        old = ["-m owner --uid-owner debian-tor -j RETURN",
               "-m owner --uid-owner systemd-resolve -p tcp --dport 853 -j REDIRECT --to-ports 5353",
               "-p udp --dport 53 -j REDIRECT --to-ports 5353", "-p tcp --dport 53 -j REDIRECT --to-ports 5353"]
        self.run_tool(self.tool.dns_protect_on)
        self.fake.tables["v4"]["nat"]["chains"]["SHADOWDNS"] = list(old)   # as the previous version loaded it
        self.assertTrue(self.tool._chain_outdated("SHADOWDNS"))
        self.run_tool(self.tool.boot)
        self.assertFalse(self.tool._chain_outdated("SHADOWDNS"))
        self.assertEqual(self.fake.nat("SHADOWDNS"), [" ".join(r) for r in self.tool.dns_rules()])
        self.assertEqual(self.fake.hooks["nat"].count("SHADOWDNS"), 1)

    def test_boot_without_tor_hands_dns_back(self):
        self.protect_then_restart()
        self.tor_installed = False
        self.run_tool(self.tool.boot)
        self.assertFalse(os.path.exists(self.tool.NM_DNS_CONF))
        self.assertEqual(self.resolv(), NM_TEXT)
        self.assertFalse(self.fake.immutable)
        self.assertFalse(self.tool.tor_dns_redirect_active())
        self.assertFalse(self.state()["dns_protected"])

    def test_boot_writes_a_missing_tor_dns_config(self):
        self.protect_then_restart()
        os.unlink(self.tool.TORDNS_CF)
        self.run_tool(self.tool.boot)
        with open(self.tool.TORDNS_CF) as f:
            self.assertIn("DNSPort 127.0.0.1:26", f.read())
        # A restart: Tor exits on a reload that changes KeepBindCapabilities.
        self.assertIn(["systemctl", "restart", "--no-block", "tor@default"], self.fake.calls)
        self.assertFalse([c for c in self.fake.calls if "reload-or-restart" in c])
        self.assertTrue(self.tool.tor_dns_redirect_active())

    def test_boot_without_protection_changes_nothing(self):
        # (Tor's SOCKS ports file and the redirect of 9050 are in place, as
        # after the first boot of this version:
        # test_boot_gives_tor_a_socks_port_no_user_can_take.)
        with redirect_stdout(io.StringIO()):
            self.tool._ensure_torrc_d()
            self.tool.socks_redirect_on()
        self.fake.calls.clear()
        self.run_tool(self.tool.boot)
        self.assertEqual(self.resolv(), NM_TEXT)
        self.assertEqual(self.fake.hooks, {"filter": [], "nat": ["SHADOWSOCKS"]})
        self.assertFalse([c for c in self.fake.calls if c[0] in ("iptables", "ip6tables")
                          and not {"-S", "-L"} & set(c)])                  # nothing loaded or removed
        self.assertFalse([c for c in self.fake.calls if c[0] in ("chattr", "nmcli")
                          or (c[0] == "systemctl" and c[1] not in ("is-system-running", "is-active"))])
        self.assertFalse([c for c in self.fake.calls if c[:2] == ["shadow-killswitch", "set"]])
        st = self.state()
        self.assertFalse(st["dns_protected"] or st["transparent_proxy"] or st["kill_switch"] or st["ghost_mode"])
        self.assertIsNone(st["error"])

    def test_state_after_restart_is_the_truth(self):
        # Ghost Mode before the restart: its rules end with it, DNS stays.
        with open(self.tool.STATE_FILE, "w") as f:
            json.dump({"ghost_mode": True, "threat_model": "maximum", "transparent_proxy": True,
                       "kill_switch": True, "dns_protected": True}, f)
        self.run_tool(self.tool.dns_protect_on)
        st_before = self.tool.load_state()
        self.assertTrue(st_before["ghost_mode"])
        self.fake.restart()
        with open(self.tool.STATE_FILE, "w") as f:    # even if /run had survived
            json.dump(st_before, f)
        self.run_tool(self.tool.boot)
        st = self.state()
        self.assertFalse(st["ghost_mode"])
        self.assertFalse(st["transparent_proxy"])
        self.assertFalse(st["kill_switch"])
        self.assertTrue(st["dns_protected"])
        self.assertEqual(st["threat_model"], "enhanced")

    def test_boot_while_an_old_ghost_mode_runs_replaces_its_kill_switch(self):
        # The package runs "boot" on upgrade while an older version's Ghost
        # Mode is on: its iptables kill switch is replaced by shadow-killswitch
        # (engaged FIRST, so nothing leaks in between), its proxy gets the
        # .onion rule, and everything is reported as it really is.
        t = self.tool
        nat = self.fake.tables["v4"]["nat"]
        nat["chains"]["SHADOWTOR"] = ["-p tcp --syn -j REDIRECT --to-ports 9040"]
        nat["hooks"].append("SHADOWTOR")
        for fam in ("v4", "v6"):
            self.fake.tables[fam]["filter"]["chains"]["SHADOWKILL"] = ["-j DROP"]
            self.fake.tables[fam]["filter"]["hooks"].append("SHADOWKILL")
        with open(t.STATE_FILE, "w") as f:
            json.dump({"ghost_mode": True, "threat_model": "maximum"}, f)
        with open(t.RESOLV, "w") as f:
            f.write(t.RESOLV_TOR)
        with open(t.NM_DNS_CONF, "w") as f:
            f.write("[main]\ndns=none\n")
        os.makedirs(t.TORRC_D, exist_ok=True)
        with open(t.TORDNS_CF, "w") as f:
            f.write("DNSPort 127.0.0.1:5353\n")
        self.run_tool(t.boot)
        set_tor = self.fake.calls.index(["shadow-killswitch", "set", "tor", "--no-lan", "--runtime"])

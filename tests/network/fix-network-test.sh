#!/usr/bin/env bash
# Tests scripts/fix-network.sh against a simulated laptop (fake_system.py):
# every repair path, the verdicts, idempotence, --report-only, --keep-hide-me,
# the undo script and the report (no hardware addresses in it).
#
#     bash tests/network/fix-network-test.sh [scenario...]
#
# SHOW=1 prints the script's output. Needs bash, python3 and coreutils only; runs as any user, touches nothing
# outside a temporary directory.
# shellcheck disable=SC2012  # ls on our own temporary paths
set -u
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)
SCRIPT=$REPO/scripts/fix-network.sh
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
PASSED=0 FAILED=0 FAILS=()

BIN=$WORK/bin
mkdir -p "$BIN"
for t in nmcli ip curl ping getent rfkill systemctl iptables ip6tables ss modinfo sysctl chattr lsattr shadow-anon update-initramfs; do
    ln -s "$HERE/fake_system.py" "$BIN/$t"
done
# sudo must never be needed: the tests run the script as "root" via a fake id.
cat >"$BIN/id" <<'EOF'
#!/bin/sh
[ "${1:-}" = -u ] && { echo 0; exit 0; }
exec /usr/bin/id "$@"
EOF
chmod +x "$BIN/id"

# setup NAME SCENARIO JSON-OVERRIDES -> fresh root and state for one case
setup() {
    CASE=$1
    export FAKE_ROOT=$WORK/$CASE/root FAKE_STATE=$WORK/$CASE/state.json
    export SHADOW_NETFIX_ROOT=$FAKE_ROOT SHADOW_NETFIX_STATE=$WORK/$CASE/user-state SHADOW_NETFIX_WAIT=0
    mkdir -p "$FAKE_ROOT"/{etc/NetworkManager/conf.d,usr/lib/NetworkManager/conf.d,run/NetworkManager,etc/sysctl.d,etc/modprobe.d}
    for d in all default wlan0 eno1; do
        mkdir -p "$FAKE_ROOT/proc/sys/net/ipv4/conf/$d"
        echo 1 >"$FAKE_ROOT/proc/sys/net/ipv4/conf/$d/rp_filter"
    done
    mkdir -p "$FAKE_ROOT/sys/class/net/wlan0/device" "$FAKE_ROOT/sys/class/net/eno1/device"
    ln -s ../../../../bus/pci/drivers/rtw88_8822ce "$FAKE_ROOT/sys/class/net/wlan0/device/driver"
    ln -s ../../../../bus/pci/drivers/e1000e "$FAKE_ROOT/sys/class/net/eno1/device/driver"
    cp "$REPO/security/hardening/NetworkManager/80-shadow-privacy.conf" "$FAKE_ROOT/usr/lib/NetworkManager/conf.d/"
    # The 0.2.0 image: a new random Wi-Fi address at every connection.
    sed -i 's/^wifi.cloned-mac-address=.*/wifi.cloned-mac-address=random/' "$FAKE_ROOT/usr/lib/NetworkManager/conf.d/80-shadow-privacy.conf"
    printf 'PRETTY_NAME="Shadow OS 0.2.0"\n' >"$FAKE_ROOT/etc/os-release"
    printf '# Generated by NetworkManager\nnameserver 192.168.1.1\n' >"$FAKE_ROOT/etc/resolv.conf"
    python3 - "$2" "$3" <<'EOF'
import json, os, sys
scenario, extra = sys.argv[1], json.loads(sys.argv[2] or "{}")
st = {"scenario": scenario, "radio": "enabled", "rotation": False, "tor_ok": False,
      "saved_wifi": True, "wifi_uuid": "u-wifi",
      "devices": {"wlan0": {"type": "wifi", "state": "connected", "con": "u-wifi"},
                  "eno1": {"type": "ethernet", "state": "connected", "con": "u-eth"}},
      "cons": {"u-wifi": {"id": "HomeNet", "type": "wifi", "mac": "", "powersave": "0", "dns": ""},
               "u-eth": {"id": "Wired", "type": "ethernet", "mac": "", "dns": ""}},
      "chains": {"filter": [], "nat": []}, "hooks": {"filter": [], "nat": []}}
for k, v in extra.items():
    if k == "eth_down":
        st["devices"]["eno1"]["state"] = "unavailable"; st["devices"]["eno1"]["con"] = ""
    elif k == "wifi_down":
        st["devices"]["wlan0"]["state"] = "disconnected"; st["devices"]["wlan0"]["con"] = ""
    else:
        st[k] = v
json.dump(st, open(os.environ["FAKE_STATE"], "w"))
EOF
    [ "${RP_LOOSE:-0}" = 1 ] && for d in all default wlan0 eno1; do echo 2 >"$FAKE_ROOT/proc/sys/net/ipv4/conf/$d/rp_filter"; done
    return 0
}

run() {   # run [options] -> OUT, RC
    OUT=$(PATH="$BIN:$PATH" bash "$SCRIPT" --yes "$@" </dev/null 2>&1)
    RC=$?
    if [ -n "${SHOW:-}" ]; then printf '%s\n[exit %s]\n' "$OUT" "$RC"; fi
}
st() { python3 -c "import json,os; s=json.load(open(os.environ['FAKE_STATE'])); print($1)"; }

check() {   # check "description" condition...
    local what=$1; shift
    if "$@"; then PASSED=$((PASSED + 1)); else FAILED=$((FAILED + 1)); FAILS+=("$CASE: $what"); fi
}
has()    { grep -qF -- "$1" <<<"$OUT"; }
hasnt()  { ! grep -qF -- "$1" <<<"$OUT"; }
rc_is()  { [ "$RC" = "$1" ]; }
file_has() { grep -qF -- "$2" "$1" 2>/dev/null; }
eq()     { [ "$1" = "$2" ]; }
report_clean() {   # no hardware address, no Wi-Fi password field
    ! grep -qiE '([0-9a-f]{2}:){5}[0-9a-f]{2}' "$SHADOW_NETFIX_STATE/report.txt" &&
        ! grep -qi 'psk' "$SHADOW_NETFIX_STATE/report.txt"
}
undo_ok() { local u; u=$(ls "$SHADOW_NETFIX_STATE"/backup-*/undo.sh 2>/dev/null | head -n1); [ -n "$u" ] && sh -n "$u" && grep -qF -- "$1" "$u"; }

want() { [ $# = 0 ] || [ -z "${ONLY:-}" ] || [[ " $ONLY " == *" $1 "* ]]; }
ONLY="$*"

# ---------------------------------------------------------------------------------
if want good; then
    RP_LOOSE=1 setup good none '{}'
    run
    check "PASS" rc_is 0
    check "Wi-Fi works" has "OK    wlan0"
    check "no sysctl file when not strict" eq "$(ls "$FAKE_ROOT/etc/sysctl.d")" ""
    check "stable MAC default written" file_has "$FAKE_ROOT/etc/NetworkManager/conf.d/81-shadow-wifi-mac.conf" "wifi.cloned-mac-address=stable"
    check "report clean" report_clean
    run
    check "second run PASS" rc_is 0
    check "second run changes nothing" has "Nothing was changed."
fi

if want rp; then
    setup rp rp '{}'
    run
    check "PASS" rc_is 0
    check "rp_filter loose in file" file_has "$FAKE_ROOT/etc/sysctl.d/95-shadow-network.conf" "net.ipv4.conf.all.rp_filter = 2"
    check "rp_filter loose now" eq "$(cat "$FAKE_ROOT/proc/sys/net/ipv4/conf/all/rp_filter")" 2
    check "said so" has "strict -> loose"
    check "Wi-Fi not reconnected (no repair needed)" eq "$(st 's.get("reconnects",0)')" 0
    check "undo restores rp_filter" undo_ok "rp_filter=1"
    check "cable note" has "unplug it and Wi-Fi takes over"
fi

if want random; then
    setup random random '{"eth_down": 1}'
    run
    check "PASS" rc_is 0
    check "fixed by the stable address" has "stable private address"
    check "profile keeps default (global stable)" eq "$(st 's["cons"]["u-wifi"]["mac"]')" ""
fi

if want random-explicit; then
    setup random-explicit random '{"eth_down": 1}'
    python3 -c "import json,os;p=os.environ['FAKE_STATE'];s=json.load(open(p));s['cons']['u-wifi']['mac']='random';json.dump(s,open(p,'w'))"
    run
    check "PASS" rc_is 0
    check "per-network random replaced by stable" eq "$(st 's["cons"]["u-wifi"]["mac"]')" stable
    check "undo puts random back" undo_ok "cloned-mac-address random"
fi

if want macfilter; then
    setup macfilter macfilter '{"eth_down": 1}'
    run
    check "PASS" rc_is 0
    check "real address kept for this network" eq "$(st 's["cons"]["u-wifi"]["mac"]')" permanent
    check "power saving put back (did not help)" eq "$(st 's["cons"]["u-wifi"]["powersave"]')" 0
    check "explained" has "uses the real hardware address"
    check "undo restores the address policy" undo_ok "802-11-wireless.cloned-mac-address ''"
fi

if want powersave; then
    setup powersave powersave '{"eth_down": 1}'
    run
    check "PASS" rc_is 0
    check "power saving off" eq "$(st 's["cons"]["u-wifi"]["powersave"]')" 2
    check "real address not used" eq "$(st 's["cons"]["u-wifi"]["mac"]')" ""
fi

if want routerdns; then
    setup routerdns routerdns '{"eth_down": 1}'
    run
    check "PASS" rc_is 0
    check "public DNS for this network" eq "$(st 's["cons"]["u-wifi"]["dns"]')" "9.9.9.9,1.1.1.1"
    check "explained" has "DNS servers 9.9.9.9 and 1.1.1.1 added"
fi

if want tordns; then
    setup tordns none '{"immutable": true}'
    printf '# Shadow OS — DNS routed through Tor'"'"'s DNSPort\nnameserver 127.0.0.1\noptions ndots:0 edns0\n' >"$FAKE_ROOT/etc/resolv.conf"
    printf '[main]\ndns=none\n' >"$FAKE_ROOT/etc/NetworkManager/conf.d/90-shadow-dns.conf"
    printf 'nameserver 10.9.9.9\n' >"$FAKE_ROOT/etc/resolv.conf.shadow-backup"
    run
    check "PASS" rc_is 0
    check "NetworkManager writes DNS again" file_has "$FAKE_ROOT/etc/resolv.conf" "Generated by NetworkManager"
    check "lock removed" eq "$(ls "$FAKE_ROOT/etc/NetworkManager/conf.d/")" "81-shadow-wifi-mac.conf"
    check "stale backup moved away" eq "$(ls "$FAKE_ROOT/etc/resolv.conf.shadow-backup" 2>/dev/null)" ""
    check "immutable flag cleared first" eq "$(st 's["immutable"]')" False
    check "undo can restore the Tor resolv.conf" undo_ok "/etc/resolv.conf"
fi

if want resolv-dangling; then
    setup resolv-dangling none '{}'
    rm "$FAKE_ROOT/etc/resolv.conf"; ln -s ../run/systemd/resolve/stub-resolv.conf "$FAKE_ROOT/etc/resolv.conf"
    run
    check "PASS" rc_is 0
    check "explained" has "which does not exist"
fi

if want rotation; then
    setup rotation rotation '{"rotation": true}'
    run
    check "PASS" rc_is 0
    check "rotation stopped" eq "$(st 's["rotation"]')" False
    check "undo re-enables it" undo_ok "enable --now shadow-anon-rotate.timer"
fi

if want keep-hide-me; then
    setup keep-hide-me rotation '{"rotation": true}'
    run --keep-hide-me
    check "not fixed while rotation is kept" rc_is 4
    check "says the rotation is the problem" has "identity rotation is on"
    check "rotation untouched" eq "$(st 's["rotation"]')" True
fi

if want ghost-broken; then
    setup ghost-broken none '{"chains": {"filter": ["SHADOWKILL"], "nat": ["SHADOWTOR", "SHADOWDNS"]}, "hooks": {"filter": ["SHADOWKILL"], "nat": ["SHADOWTOR", "SHADOWDNS"]}}'
    printf '# Shadow OS — DNS routed through Tor'"'"'s DNSPort\nnameserver 127.0.0.1\n' >"$FAKE_ROOT/etc/resolv.conf"
    printf '[main]\ndns=none\n' >"$FAKE_ROOT/etc/NetworkManager/conf.d/90-shadow-dns.conf"
    run
    check "PASS" rc_is 0
    check "Ghost Mode network part off" has "Ghost Mode's network part is off"
    check "chains unhooked" eq "$(st 's["hooks"]')" "{'filter': [], 'nat': []}"
fi

if want ghost-working; then
    setup ghost-working none '{"tor_ok": true, "immutable": true, "chains": {"filter": ["SHADOWKILL"], "nat": ["SHADOWTOR"]}, "hooks": {"filter": ["SHADOWKILL"], "nat": ["SHADOWTOR"]}}'
    printf '# Shadow OS — DNS routed through Tor'"'"'s DNSPort\nnameserver 127.0.0.1\n' >"$FAKE_ROOT/etc/resolv.conf"
    printf '[main]\ndns=none\n' >"$FAKE_ROOT/etc/NetworkManager/conf.d/90-shadow-dns.conf"
    run
    check "PASS through Tor" rc_is 0
    check "says through Tor" has "(through Tor)"
    check "Ghost Mode left on" eq "$(st 's["hooks"]["filter"]')" "['SHADOWKILL']"
    check "Tor DNS left alone" file_has "$FAKE_ROOT/etc/resolv.conf" "routed through Tor"
fi

if want portal; then
    setup portal portal '{"eth_down": 1}'
    run
    check "FAIL" rc_is 1
    check "tells to sign in" has "neverssl.com"
    check "real address not used" eq "$(st 's["cons"]["u-wifi"]["mac"]')" ""
fi

if want driver; then
    setup driver driver '{"eth_down": 1}'
    run
    check "RESTART NEEDED" rc_is 4
    check "driver options written" file_has "$FAKE_ROOT/etc/modprobe.d/shadow-wifi-fix.conf" "options rtw88_core disable_lps_deep=y"
    check "only options the driver has" file_has "$FAKE_ROOT/etc/modprobe.d/shadow-wifi-fix.conf" "options rtw88_pci disable_aspm=y"
    check "address policy put back" eq "$(st 's["cons"]["u-wifi"]["mac"]')" ""
    check "power saving put back" eq "$(st 's["cons"]["u-wifi"]["powersave"]')" 0
    check "report clean" report_clean
    run
    check "after restart, still broken: FAIL with report" rc_is 1
    check "names the report" has "report.txt"
fi

if want wifi-off-nosaved; then
    setup wifi-off-nosaved none '{"wifi_down": 1, "saved_wifi": false}'
    run
    check "NOT VERIFIED" rc_is 3
    check "says connect first" has "Connect to your Wi-Fi from the top bar"
fi

if want wifi-off-saved; then
    setup wifi-off-saved none '{"wifi_down": 1}'
    run
    check "PASS" rc_is 0
    check "joined the saved network" eq "$(st 's["devices"]["wlan0"]["state"]')" connected
fi

if want softblock; then
    setup softblock none '{"wifi_down": 1, "rfkill_soft": true, "radio": "disabled"}'
    run
    check "PASS" rc_is 0
    check "radio on" eq "$(st 's["radio"]')" enabled
    check "unblocked" eq "$(st 's["rfkill_soft"]')" False
fi

if want hardblock; then
    setup hardblock none '{"wifi_down": 1, "rfkill_hard": true, "saved_wifi": true}'
    run
    check "FAIL" rc_is 1
    check "hardware switch named" has "hardware switch or key"
fi

if want report-only; then
    setup report-only rp '{"rotation": true}'
    run --report-only
    check "nothing written" eq "$(ls "$FAKE_ROOT/etc/sysctl.d" "$FAKE_ROOT/etc/NetworkManager/conf.d" | tr -d '\n')" "$FAKE_ROOT/etc/NetworkManager/conf.d:$FAKE_ROOT/etc/sysctl.d:"
    check "rotation untouched" eq "$(st 's["rotation"]')" True
    check "no reconnects" eq "$(st 's.get("reconnects",0)')" 0
    check "Nothing was changed" has "Nothing was changed."
fi

echo
echo "fix-network tests: $PASSED passed, $FAILED failed"
for f in "${FAILS[@]}"; do echo "  FAILED: $f"; done
[ "$FAILED" = 0 ]

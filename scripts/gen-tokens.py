#!/usr/bin/env python3
"""Generate artefacts from the NEXUS design tokens.

    gen-tokens.py qml    <out.qml>                      QML Theme singleton
    gen-tokens.py render <template> <out> [--mode dark|light] [--accent NAME]
    gen-tokens.py docs   <out.md>                       token reference (Markdown)
    gen-tokens.py check                                 validate the token file

The token file (desktop/themes/tokens/nexus-tokens.json) is the single source
of truth for colours, typography, spacing, radii, motion and elevation.

Template placeholders understood by "render":

    @{bgBase}                 semantic colour for the selected mode  → #RRGGBB
    @{accent}                 selected accent for the selected mode  → #RRGGBB
    @{accent.violet}          a specific accent                      → #RRGGBB
    @{brand.gradientStart}    any scalar by dotted path
    @{font.ui} @{fontSize.body} @{space.md} @{radius.md} @{size.rowHeight} @{motion.fast}
    @{rgb:bgBase}             "r,g,b"            (KDE colour schemes)
    @{rgba:accent:0.16}       "rgba(r, g, b, a)" (Qt style sheets, CSS)
    @{argb:accent:0.16}       "#AARRGGBB"        (QML, Qt)
    @{mix:bgBase:accent:0.12} blend of two colours → #RRGGBB
    @{mode}                   "dark" or "light"

Standard library only.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "desktop/themes/tokens/nexus-tokens.json"

HEX = re.compile(r"^#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$")


def load() -> dict:
    with open(TOKENS, encoding="utf-8") as fh:
        return json.load(fh)


def parse_color(value: str) -> tuple[int, int, int, float]:
    """#RRGGBB or #AARRGGBB → (r, g, b, alpha 0..1)."""
    if not HEX.match(value):
        raise ValueError(f"not a colour: {value!r}")
    h = value[1:]
    a = 1.0
    if len(h) == 8:
        a = int(h[0:2], 16) / 255
        h = h[2:]
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), a


def to_hex(r: float, g: float, b: float) -> str:
    return "#{:02X}{:02X}{:02X}".format(*(max(0, min(255, round(c))) for c in (r, g, b)))


def mix(c1: str, c2: str, t: float) -> str:
    r1, g1, b1, _ = parse_color(c1)
    r2, g2, b2, _ = parse_color(c2)
    return to_hex(r1 + (r2 - r1) * t, g1 + (g2 - g1) * t, b1 + (b2 - b1) * t)


def check(tok: dict) -> list[str]:
    errors = []
    dark, light = tok["color"]["dark"], tok["color"]["light"]
    if set(dark) != set(light):
        errors.append(f"dark/light colour sets differ: {sorted(set(dark) ^ set(light))}")
    for mode in ("dark", "light"):
        for k, v in tok["color"][mode].items():
            if not HEX.match(v):
                errors.append(f"color.{mode}.{k}: invalid colour {v!r}")
    for name, a in tok["accent"].items():
        for mode in ("dark", "light"):
            if not HEX.match(a.get(mode, "")):
                errors.append(f"accent.{name}.{mode}: invalid colour")
    if tok["accentDefault"] not in tok["accent"]:
        errors.append("accentDefault does not name an accent")
    for k, v in tok["easing"].items():
        if len(v) != 4:
            errors.append(f"easing.{k}: need 4 control values")

    # WCAG contrast of body text on the base background must reach AA (4.5:1).
    def lum(c: str) -> float:
        r, g, b, _ = parse_color(c)
        ch = [(x / 255) for x in (r, g, b)]
        ch = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in ch]
        return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2]

    def contrast(a: str, b: str) -> float:
        la, lb = sorted((lum(a), lum(b)), reverse=True)
        return (la + 0.05) / (lb + 0.05)

    for mode in ("dark", "light"):
        c = tok["color"][mode]
        for fg, bg, minimum in (("textPrimary", "bgBase", 7.0), ("textSecondary", "bgBase", 4.5),
                                ("textSecondary", "bgRaised", 4.5), ("textMuted", "bgBase", 3.0)):
            ratio = contrast(c[fg], c[bg])
            if ratio < minimum:
                errors.append(f"{mode}: contrast {fg} on {bg} is {ratio:.2f}:1 (< {minimum}:1)")
        for name, a in tok["accent"].items():
            ratio = contrast(a[mode], c["bgBase"])
            if ratio < 3.0:
                errors.append(f"{mode}: accent {name} on bgBase is {ratio:.2f}:1 (< 3:1)")
            ratio = contrast(c["textOnAccent"], a[mode])
            if ratio < 4.5:
                errors.append(f"{mode}: textOnAccent on accent {name} is {ratio:.2f}:1 (< 4.5:1)")
    return errors


def cap(s: str) -> str:
    return s[:1].upper() + s[1:]


def gen_qml(tok: dict) -> str:
    L: list[str] = []
    w = L.append
    w("// GENERATED by scripts/gen-tokens.py from desktop/themes/tokens/nexus-tokens.json — DO NOT EDIT.")
    w("pragma Singleton")
    w("import QtQuick")
    w("import org.nexus.ui")
    w("")
    w("QtObject {")
    w("    id: theme")
    w("")
    w("    // Live appearance state (persisted in ~/.config/nexus/appearance.conf and")
    w("    // shared by every NEXUS process through the Appearance singleton).")
    w("    readonly property bool dark: Appearance.dark")
    w("    readonly property string accentName: Appearance.accent")
    w("    readonly property bool reduceMotion: Appearance.reduceMotion")
    w("")
    w("    // ---- semantic colours -------------------------------------------------")
    for k in tok["color"]["dark"]:
        w(f'    readonly property color {k}: dark ? "{tok["color"]["dark"][k]}" : "{tok["color"]["light"][k]}"')
    w("")
    w("    // ---- accents -----------------------------------------------------------")
    w("    readonly property var accentNames: [" + ", ".join(f'"{n}"' for n in tok["accent"]) + "]")
    w("    readonly property var accentLabels: ({ " + ", ".join(
        f'"{n}": "{a["label"]}"' for n, a in tok["accent"].items()) + " })")
    for n, a in tok["accent"].items():
        w(f'    readonly property color accent{cap(n)}: dark ? "{a["dark"]}" : "{a["light"]}"')
    w("    readonly property color accent: {")
    w("        switch (accentName) {")
    for n in tok["accent"]:
        w(f'        case "{n}": return accent{cap(n)}')
    w(f'        default: return accent{cap(tok["accentDefault"])}')
    w("        }")
    w("    }")
    w("    function accentByName(name) {")
    w("        switch (name) {")
    for n in tok["accent"]:
        w(f'        case "{n}": return accent{cap(n)}')
    w(f'        default: return accent{cap(tok["accentDefault"])}')
    w("        }")
    w("    }")
    w("")
    w("    // ---- brand ---------------------------------------------------------------")
    for k, v in tok["brand"].items():
        w(f'    readonly property color brand{cap(k)}: "{v}"')
    w("")
    w("    // ---- derived colours -----------------------------------------------------")
    op = tok["opacity"]
    w(f"    readonly property color accentFill: alpha(accent, {op['selectedFill']})")
    w("    readonly property color accentFillStrong: alpha(accent, 0.28)")
    w("    readonly property color accentHover: Qt.lighter(accent, dark ? 1.12 : 0.92)")
    w("    readonly property color accentPressed: Qt.darker(accent, dark ? 1.15 : 1.1)")
    w(f"    readonly property color hoverOverlay: alpha(textPrimary, {op['hoverOverlay']})")
    w(f"    readonly property color pressedOverlay: alpha(textPrimary, {op['pressedOverlay']})")
    w(f"    readonly property color glassPanel: alpha(bgSurface, {op['glassPanel']})")
    w(f"    readonly property color glassPopup: alpha(bgOverlay, {op['glassPopup']})")
    w("    readonly property color successFill: alpha(success, 0.14)")
    w("    readonly property color warningFill: alpha(warning, 0.14)")
    w("    readonly property color dangerFill: alpha(danger, 0.14)")
    w("")
    w("    // ---- typography ----------------------------------------------------------")
    w(f'    readonly property string fontUi: "{tok["font"]["ui"]}"')
    w(f'    readonly property string fontMono: "{tok["font"]["mono"]}"')
    for k, v in tok["fontSize"].items():
        w(f"    readonly property int fontSize{cap(k)}: {v}")
    for k, v in tok["fontWeight"].items():
        w(f"    readonly property int weight{cap(k)}: {v}")
    w("")
    w("    // ---- spacing / radius / sizes -------------------------------------------")
    for k, v in tok["space"].items():
        w(f"    readonly property int space{cap(k)}: {v}")
    for k, v in tok["radius"].items():
        w(f"    readonly property int radius{cap(k)}: {v}")
    for k, v in tok["size"].items():
        w(f"    readonly property int {k}: {v}")
    w("")
    w("    // ---- motion (durations collapse to 0 when 'reduce motion' is on) --------")
    for k, v in tok["motion"].items():
        w(f"    readonly property int motion{cap(k)}: reduceMotion ? 0 : {v}")
    for k, v in tok["easing"].items():
        vals = ", ".join(str(x) for x in v) + ", 1.0, 1.0"
        w(f"    readonly property var easing{cap(k)}: [{vals}]")
    w("")
    w("    // ---- elevation -----------------------------------------------------------")
    for k, v in tok["elevation"].items():
        w(f"    readonly property int {k}OffsetY: {v['y']}")
        w(f"    readonly property int {k}Blur: {v['blur']}")
        w(f"    readonly property real {k}Opacity: {v['opacity']}")
    w("")
    w("    // ---- opacity -------------------------------------------------------------")
    for k, v in tok["opacity"].items():
        w(f"    readonly property real opacity{cap(k)}: {v}")
    w("")
    w("    // ---- helpers -------------------------------------------------------------")
    w("    function alpha(c, a) { return Qt.rgba(c.r, c.g, c.b, a) }")
    w("    function mix(a, b, t) {")
    w("        return Qt.rgba(a.r + (b.r - a.r) * t, a.g + (b.g - a.g) * t, a.b + (b.b - a.b) * t, a.a + (b.a - a.a) * t)")
    w("    }")
    w("    // Human-readable byte counts (IEC units), used across the system apps.")
    w("    function formatBytes(bytes, decimals) {")
    w("        if (bytes === undefined || bytes === null || isNaN(bytes)) return \"—\"")
    w("        var units = [\"B\", \"KiB\", \"MiB\", \"GiB\", \"TiB\", \"PiB\"]")
    w("        var v = Number(bytes), i = 0")
    w("        while (v >= 1024 && i < units.length - 1) { v /= 1024; i++ }")
    w("        var d = decimals === undefined ? (i === 0 ? 0 : (v < 10 ? 2 : 1)) : decimals")
    w("        return v.toFixed(d) + \" \" + units[i]")
    w("    }")
    w("    function formatRate(bytesPerSecond) { return formatBytes(bytesPerSecond) + \"/s\" }")
    w("    function formatDuration(seconds) {")
    w("        var s = Math.floor(seconds), d = Math.floor(s / 86400), h = Math.floor((s % 86400) / 3600), m = Math.floor((s % 3600) / 60)")
    w("        if (d > 0) return d + \"d \" + h + \"h\"")
    w("        if (h > 0) return h + \"h \" + m + \"m\"")
    w("        if (m > 0) return m + \"m \" + (s % 60) + \"s\"")
    w("        return s + \"s\"")
    w("    }")
    w("}")
    return "\n".join(L) + "\n"


def resolver(tok: dict, mode: str, accent: str):
    colors = tok["color"][mode]
    acc = tok["accent"]

    def color(name: str) -> str:
        if name == "accent":
            return acc[accent][mode]
        if name.startswith("accent."):
            return acc[name.split(".", 1)[1]][mode]
        if name in colors:
            return colors[name]
        if name.startswith("brand."):
            return tok["brand"][name.split(".", 1)[1]]
        if HEX.match(name):
            return name
        raise KeyError(f"unknown colour token {name!r}")

    def scalar(path: str):
        node = tok
        for part in path.split("."):
            node = node[part]
        if isinstance(node, (dict, list)):
            raise KeyError(f"token {path!r} is not a scalar")
        return node

    def resolve(expr: str) -> str:
        if expr == "mode":
            return mode
        if ":" in expr:
            fn, *args = expr.split(":")
            if fn == "rgb":
                r, g, b, _ = parse_color(color(args[0]))
                return f"{r},{g},{b}"
            if fn == "rgba":
                r, g, b, _ = parse_color(color(args[0]))
                return f"rgba({r}, {g}, {b}, {float(args[1]):g})"
            if fn == "argb":
                r, g, b, _ = parse_color(color(args[0]))
                return "#{:02X}{:02X}{:02X}{:02X}".format(round(float(args[1]) * 255), r, g, b)
            if fn == "mix":
                return mix(color(args[0]), color(args[1]), float(args[2]))
            raise KeyError(f"unknown function {fn!r}")
        try:
            c = color(expr)
            r, g, b, a = parse_color(c)
            return to_hex(r, g, b) if a == 1.0 else c
        except KeyError:
            return str(scalar(expr))

    return resolve


def render(tok: dict, template: str, mode: str, accent: str) -> str:
    resolve = resolver(tok, mode, accent)

    def sub(m: re.Match) -> str:
        try:
            return resolve(m.group(1))
        except (KeyError, ValueError, IndexError) as exc:
            raise SystemExit(f"gen-tokens: cannot resolve @{{{m.group(1)}}}: {exc}")

    return re.sub(r"@\{([^}]+)\}", sub, template)


def gen_docs(tok: dict) -> str:
    L = ["# NEXUS design tokens", "",
         "> Generated by `scripts/gen-tokens.py docs` from "
         "`desktop/themes/tokens/nexus-tokens.json`. Do not edit by hand.", "",
         "## Semantic colours", "", "| Token | Dark | Light |", "|---|---|---|"]
    for k in tok["color"]["dark"]:
        L.append(f"| `{k}` | `{tok['color']['dark'][k]}` | `{tok['color']['light'][k]}` |")
    L += ["", "## Accent colours", "", "| Name | Label | Dark | Light |", "|---|---|---|---|"]
    for n, a in tok["accent"].items():
        default = " (default)" if n == tok["accentDefault"] else ""
        L.append(f"| `{n}`{default} | {a['label']} | `{a['dark']}` | `{a['light']}` |")
    L += ["", "## Brand", "", "| Token | Value |", "|---|---|"]
    L += [f"| `{k}` | `{v}` |" for k, v in tok["brand"].items()]
    for title, key, unit in (("Typography — sizes", "fontSize", "px"), ("Typography — weights", "fontWeight", ""),
                             ("Spacing", "space", "px"), ("Corner radius", "radius", "px"),
                             ("Component sizes", "size", "px"), ("Motion durations", "motion", "ms")):
        L += ["", f"## {title}", "", "| Token | Value |", "|---|---|"]
        L += [f"| `{k}` | {v}{(' ' + unit) if unit else ''} |" for k, v in tok[key].items()]
    L += ["", "## Fonts", "", "| Role | Family |", "|---|---|"]
    L += [f"| `{k}` | {v} |" for k, v in tok["font"].items()]
    L += ["", "## Easing curves (cubic Bézier)", "", "| Token | Control points |", "|---|---|"]
    L += [f"| `{k}` | `{', '.join(map(str, v))}` |" for k, v in tok["easing"].items()]
    L += ["", "## Elevation", "", "| Level | Offset Y | Blur | Opacity |", "|---|---|---|---|"]
    L += [f"| `{k}` | {v['y']} px | {v['blur']} px | {v['opacity']} |" for k, v in tok["elevation"].items()]
    L += ["", "## Opacity", "", "| Token | Value |", "|---|---|"]
    L += [f"| `{k}` | {v} |" for k, v in tok["opacity"].items()]
    return "\n".join(L) + "\n"


def write(path: str, content: str):
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    if p.exists() and p.read_text(encoding="utf-8") == content:
        return                              # keep mtime stable for incremental builds
    p.write_text(content, encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    q = sub.add_parser("qml"); q.add_argument("out")
    r = sub.add_parser("render"); r.add_argument("template"); r.add_argument("out")
    r.add_argument("--mode", choices=["dark", "light"], default="dark"); r.add_argument("--accent", default=None)
    d = sub.add_parser("docs"); d.add_argument("out")
    sub.add_parser("check")
    args = ap.parse_args()

    tok = load()
    errors = check(tok)
    if errors:
        for e in errors:
            print(f"gen-tokens: {e}", file=sys.stderr)
        return 1
    if args.cmd == "check":
        print("tokens OK")
    elif args.cmd == "qml":
        write(args.out, gen_qml(tok))
    elif args.cmd == "render":
        accent = args.accent or tok["accentDefault"]
        if accent not in tok["accent"]:
            print(f"gen-tokens: unknown accent {accent!r}", file=sys.stderr)
            return 1
        write(args.out, render(tok, Path(args.template).read_text(encoding="utf-8"), args.mode, accent))
    elif args.cmd == "docs":
        write(args.out, gen_docs(tok))
    return 0


if __name__ == "__main__":
    sys.exit(main())
